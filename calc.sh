#!/bin/sh
# 연습용 계산 함수 — work-loop 리허설에서 코드 변경·충돌을 만들 때 쓴다.

# add <a> <b> — 두 정수의 합을 출력한다. 정수가 아닌 인자는 오류(종료 코드 2)로 거절한다.
add() {
  case "$1$2" in *[!0-9-]*|'') echo "add: 정수가 아님" >&2; return 2 ;; esac
  echo $(( $1 + $2 ))
}

# sub <a> <b> — 두 정수의 차(a − b)를 출력한다.
sub() { echo $(( $1 - $2 )); }

# mul <a> <b> — 두 정수의 곱을 출력한다.
mul() { echo $(( $1 * $2 )); }
